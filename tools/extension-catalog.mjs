// Writes src/extensions/catalog.js: the extensions ☰ → Extensions offers, each
// with its version (from its manifest.json) and the exact list of files its
// download zips up.
//
//   node tools/extension-catalog.mjs          # rewrite the catalog
//   node tools/extension-catalog.mjs --check  # fail if it is out of date
//
// The app has no build step, so it cannot list a folder at run time. The
// download fetches each listed file from the deployed site and zips them in the
// browser, so a file added to an extension but missing here would be silently
// left out of every download — which is what --check, run by tools/check.mjs,
// is for.
//
// What goes in a download: everything in the extension's folder except its
// tools/ (tests, fixtures, generators) and dotfiles.

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/extensions/catalog.js");

// The words the store shows. Everything else is read from disk.
export const EXTENSIONS = [
  {
    id: "recall-clipper",
    folder: "recall-clipper",
    tagline: "One extension for bringing web pages into Recall: clean a page, copy any part of it as Markdown, or save it as a PDF.",
    details: [
      "Clean this page: Auto marks ads, popups, cookie banners, sticky bars, share buttons, comments and related links (Gentle, Balanced or Reader); or click blocks yourself. Marked blocks turn blurred and red, Apply removes them, and everything can be undone.",
      "Copy as Markdown: click the blocks you want and see them exactly as Recall will show them — math, diagrams and code included — then paste into a file's Notes.",
      "Save as PDF: smart pages cut before headings and between paragraphs, about one A4 page each (or the length you choose); the breaks are shown on the page so you can drag, add or remove them first. Pictures are sized for print and shadows left out, so the PDF stays small and quick to open. Import it from My Files → Import: the file is named after the page and its Notes link back to it."
    ],
    shortcut: "Alt+Shift+C clean · Alt+Shift+M copy as Markdown · Alt+Shift+P save as PDF · Alt+Shift+O open",
    permissions: "Runs only on the tab you use it on, and uploads nothing. Saving a PDF uses Chrome's own print engine through its debugging interface, so Chrome shows a “debugging this browser” bar while it works."
  }
];

function walk(dir, base = dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith(".")) continue;
    const full = path.join(dir, name);
    const rel = path.relative(base, full).split(path.sep).join("/");
    if (statSync(full).isDirectory()) {
      if (rel === "tools") continue;
      out.push(...walk(full, base));
    } else {
      out.push({ path: rel, size: statSync(full).size });
    }
  }
  return out;
}

export function buildCatalog() {
  return EXTENSIONS.map((ext) => {
    const dir = path.join(ROOT, ext.folder);
    const manifest = JSON.parse(readFileSync(path.join(dir, "manifest.json"), "utf8"));
    const files = walk(dir);
    return {
      ...ext,
      name: manifest.name,
      version: manifest.version,
      description: manifest.description,
      bytes: files.reduce((sum, f) => sum + f.size, 0),
      files
    };
  });
}

export function renderCatalog(catalog = buildCatalog()) {
  return `// GENERATED by tools/extension-catalog.mjs — do not edit by hand.
// Run \`node tools/extension-catalog.mjs\` after changing anything in an
// extension's folder; tools/check.mjs fails while this is out of date.
//
// The browser extensions ☰ → Extensions offers. Each download fetches exactly
// these files from the deployed site and zips them (src/extensions/extension-store.js).

export const EXTENSIONS = ${JSON.stringify(catalog, null, 2)};
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = renderCatalog();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT, "utf8"); } catch { /* missing */ }
    const ok = current === text;
    console.log(ok ? "ok   src/extensions/catalog.js matches the extension folders"
      : "FAIL src/extensions/catalog.js is out of date — run: node tools/extension-catalog.mjs");
    console.log(`CHECK: 1 checks · ${ok ? 0 : 1} failed`);
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(OUT, text);
  const catalog = buildCatalog();
  catalog.forEach((e) => console.log(`${e.folder}: ${e.files.length} files, ${(e.bytes / 1048576).toFixed(2)} MB, v${e.version}`));
}
